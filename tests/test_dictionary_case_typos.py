@pytest.mark.parametrize("текст, утечка", [
    ("козлову подготовить отчёт", "козлов"),        # форма только фамилии
    ("ивану козлову подготовить отчёт", "козлов"),  # рядом с именем
    ("Козлов, подготовь отчёт", "Козлов"),          # с заглавной — как раньше
    # фамилия ровно как в списке маскируется и как обычное слово:
    # решение 30.09.2026 — утечка имени хуже искажённого текста
    ("купить 10 козлов для спортзала", "козлов"),
])
def test_фамилия_омоним_как_имя_маскируется(masker_омонимы, текст, утечка):
    out, _ = masker_омонимы.mask(текст)
    assert утечка.lower() not in out.lower(), out
    assert "[PERSON_" in out


def test_служебное_слово_в_словаре_не_маскируется(tmp_path):
    """Тестовые аккаунты вида «Владислав Исполнитель» не должны превращать
    в метку слово «исполнитель» в каждой задаче. Держится на normalize:
    известное слово в именительном фамилией не становится."""
    cfg = ShieldConfig(names=["Владислав Исполнитель"], vault_path=str(tmp_path / "v.enc"))
    masker = Masker(cfg, Vault(cfg.vault_path, Fernet.generate_key()))
    текст = "исполнитель не назначен, директор в курсе"
    out, _ = masker.mask(текст)
    assert out == текст, out
